package pack

import (
	"crypto/sha256"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

type lockEntry struct {
	Git    string `yaml:"git"`
	Ref    string `yaml:"ref"`
	Commit string `yaml:"commit"`
}

// CachePath is where a git pack is checked out. The cache is not committed;
// the lock file is.
func CachePath(root string, e Extend) string {
	sum := sha256.Sum256([]byte(e.Git + "@" + e.Ref))
	name := strings.TrimSuffix(filepath.Base(e.Git), ".git")
	return filepath.Join(root, Dir, CacheDir, fmt.Sprintf("%s-%x", name, sum[:4]))
}

func readLock(root string) []lockEntry {
	var entries []lockEntry
	if data, err := os.ReadFile(filepath.Join(root, Dir, LockFile)); err == nil {
		_ = yaml.Unmarshal(data, &entries)
	}
	return entries
}

func head(dir string) (string, error) {
	out, err := exec.Command("git", "-C", dir, "rev-parse", "HEAD").Output()
	return strings.TrimSpace(string(out)), err
}

func verifyLock(root string, e Extend, dir string) error {
	for _, l := range readLock(root) {
		if l.Git != e.Git || l.Ref != e.Ref {
			continue
		}
		got, err := head(dir)
		if err != nil {
			return fmt.Errorf("cached checkout is unreadable; run 'opine sync'")
		}
		if got != l.Commit {
			return fmt.Errorf("cached checkout is at %.12s but %s pins %.12s; run 'opine sync'", got, LockFile, l.Commit)
		}
		return nil
	}
	return fmt.Errorf("not pinned in %s; run 'opine sync'", LockFile)
}

// Sync fetches every git pack. An existing lock entry is honoured, so two
// machines resolve the same commit; update re-resolves each ref.
func Sync(root string, update bool, logf func(string, ...any)) error {
	cfg, err := readConfig(root)
	if err != nil {
		return err
	}
	old := map[string]string{}
	for _, l := range readLock(root) {
		old[l.Git+"@"+l.Ref] = l.Commit
	}
	var entries []lockEntry
	for _, e := range cfg.Extends {
		if e.Git == "" {
			continue
		}
		if e.Ref == "" {
			return fmt.Errorf("extends %s: a git pack needs a 'ref' (a tag, branch or commit)", e.Git)
		}
		dir := CachePath(root, e)
		want := old[e.Git+"@"+e.Ref]
		if update {
			want = ""
		}
		if got, err := head(dir); err == nil && want != "" && got == want {
			entries = append(entries, lockEntry{e.Git, e.Ref, got})
			logf("%s@%s up to date (%.12s)", e.Git, e.Ref, got)
			continue
		}
		if err := os.RemoveAll(dir); err != nil {
			return err
		}
		if err := os.MkdirAll(filepath.Dir(dir), 0o755); err != nil {
			return err
		}
		if out, err := exec.Command("git", "clone", "--quiet", e.Git, dir).CombinedOutput(); err != nil {
			return fmt.Errorf("clone %s: %v\n%s", e.Git, err, out)
		}
		target := e.Ref
		if want != "" {
			target = want
		}
		if out, err := exec.Command("git", "-C", dir, "checkout", "--quiet", target).CombinedOutput(); err != nil {
			return fmt.Errorf("checkout %s in %s: %v\n%s", target, e.Git, err, out)
		}
		got, err := head(dir)
		if err != nil {
			return err
		}
		entries = append(entries, lockEntry{e.Git, e.Ref, got})
		logf("%s@%s fetched (%.12s)", e.Git, e.Ref, got)
	}
	lockPath := filepath.Join(root, Dir, LockFile)
	if len(entries) == 0 {
		_ = os.Remove(lockPath)
		return nil
	}
	data, err := yaml.Marshal(entries)
	if err != nil {
		return err
	}
	header := "# Generated by 'opine sync'. Commit this file; it pins each git pack to a commit.\n"
	return os.WriteFile(lockPath, append([]byte(header), data...), 0o644)
}
