// Package emit turns the resolved conventions into the files agents and
// people read: AGENTS.md, CLAUDE.md, path-scoped rule files and the
// CONVENTIONS.md digest.
//
// What it leaves out matters as much as what it writes. Agents follow
// instructions in context files but are not helped by overviews, and every
// line costs tokens on every task, so only conventions that apply everywhere
// go into AGENTS.md, as one line each. Anything scoped to paths goes into a
// rule file the agent loads only when it touches matching files.
package emit

import (
	"fmt"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/vora-sahil/opinionated/internal/pack"
	"github.com/vora-sahil/opinionated/internal/record"
	"github.com/vora-sahil/opinionated/internal/structure"
)

const (
	Begin  = "<!-- opine:begin -->"
	End    = "<!-- opine:end -->"
	notice = "<!-- Generated by `opine emit` from .opine/. Edit there, not here. -->"

	DefaultBudget = 60

	claudeRules  = ".claude/rules/opine"
	cursorRules  = ".cursor/rules"
	copilotRules = ".github/instructions"
)

var allTargets = []string{"agents", "claude", "cursor", "copilot", "digest"}

type File struct {
	Path    string
	Content string
}

type Plan struct {
	Files    []File
	Remove   []string
	Warnings []string
}

func exists(root, p string) bool {
	_, err := os.Stat(filepath.Join(root, filepath.FromSlash(p)))
	return err == nil
}

// Targets resolves which outputs to write. Without configuration, the open
// formats are always written and tool-specific ones only where that tool is
// already in use.
func Targets(res *pack.Resolved) (map[string]bool, error) {
	t := map[string]bool{}
	if len(res.Config.Emit.Targets) > 0 {
		for _, name := range res.Config.Emit.Targets {
			ok := false
			for _, a := range allTargets {
				ok = ok || a == name
			}
			if !ok {
				return nil, fmt.Errorf("emit.targets: unknown target %q; targets are: %s", name, strings.Join(allTargets, ", "))
			}
			t[name] = true
		}
		return t, nil
	}
	t["agents"], t["claude"], t["digest"] = true, true, true
	t["cursor"] = exists(res.Root, ".cursor")
	t["copilot"] = exists(res.Root, ".github/copilot-instructions.md") || exists(res.Root, copilotRules)
	return t, nil
}

// Build computes every file emit would write, without touching the disk.
func Build(res *pack.Resolved, spec *structure.Spec) (*Plan, error) {
	targets, err := Targets(res)
	if err != nil {
		return nil, err
	}
	plan := &Plan{}
	root := res.Root

	var always, scoped []*record.Record
	for _, r := range res.Active() {
		if !r.Emit {
			continue
		}
		if global(r) {
			always = append(always, r)
		} else {
			scoped = append(scoped, r)
		}
	}

	if targets["agents"] {
		block := agentsBlock(always, len(scoped) > 0, spec)
		budget := res.Config.Emit.Budget
		if budget == 0 {
			budget = DefaultBudget
		}
		if n := strings.Count(block, "\n"); n > budget {
			plan.Warnings = append(plan.Warnings, fmt.Sprintf(
				"AGENTS.md block is %d lines (budget %d). Every line is read on every task: give conventions 'paths' so they load only where they apply, or set 'emit: false' on ones a formatter already enforces.", n, budget))
		}
		plan.add(root, "AGENTS.md", merge(read(root, "AGENTS.md"), block))
	}

	if targets["claude"] {
		if st, err := os.Lstat(filepath.Join(root, "CLAUDE.md")); err != nil {
			plan.add(root, "CLAUDE.md", "@AGENTS.md\n")
		} else if st.Mode()&os.ModeSymlink == 0 {
			cur := read(root, "CLAUDE.md")
			if strings.Contains(cur, Begin) || !strings.Contains(cur, "@AGENTS.md") {
				plan.add(root, "CLAUDE.md", merge(cur, Begin+"\n@AGENTS.md\n"+End+"\n"))
			}
		}
		plan.rules(root, claudeRules, "", ".md", scoped, func(r *record.Record) string {
			var b strings.Builder
			b.WriteString("---\npaths:\n")
			for _, p := range r.Paths {
				fmt.Fprintf(&b, "  - %q\n", p)
			}
			b.WriteString("---\n")
			b.WriteString(card(r))
			return b.String()
		})
	}
	if targets["cursor"] {
		plan.rules(root, cursorRules, "opine-", ".mdc", scoped, func(r *record.Record) string {
			return fmt.Sprintf("---\ndescription: %q\nglobs: %s\nalwaysApply: false\n---\n%s",
				r.Title, strings.Join(r.Paths, ","), card(r))
		})
	}
	if targets["copilot"] {
		plan.rules(root, copilotRules, "opine-", ".instructions.md", scoped, func(r *record.Record) string {
			return fmt.Sprintf("---\napplyTo: %q\n---\n%s", strings.Join(r.Paths, ","), card(r))
		})
	}
	if targets["digest"] {
		plan.add(root, "CONVENTIONS.md", digest(res, spec))
	}
	sort.Slice(plan.Files, func(i, j int) bool { return plan.Files[i].Path < plan.Files[j].Path })
	sort.Strings(plan.Remove)
	return plan, nil
}

// global reports whether a convention applies to the whole repository. One
// scoped to "**" does, and belongs in AGENTS.md rather than in a rule file
// that would load for every path anyway.
func global(r *record.Record) bool {
	for _, p := range r.Paths {
		if p != "**" && p != "**/*" {
			return false
		}
	}
	return true
}

func read(root, p string) string {
	data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p)))
	if err != nil {
		return ""
	}
	return string(data)
}

func (p *Plan) add(root, file, content string) {
	p.Files = append(p.Files, File{Path: file, Content: content})
}

// rules plans one file per scoped convention in a directory, and removes
// files opine wrote there earlier for conventions that no longer exist.
func (p *Plan) rules(root, dir, prefix, ext string, recs []*record.Record, render func(*record.Record) string) {
	want := map[string]bool{}
	for _, r := range recs {
		name := path.Join(dir, prefix+strings.ReplaceAll(r.ID, "/", "-")+ext)
		want[name] = true
		p.add(root, name, render(r))
	}
	entries, _ := os.ReadDir(filepath.Join(root, filepath.FromSlash(dir)))
	for _, e := range entries {
		name := path.Join(dir, e.Name())
		if !e.IsDir() && strings.HasPrefix(e.Name(), prefix) && strings.HasSuffix(e.Name(), ext) && !want[name] {
			p.Remove = append(p.Remove, name)
		}
	}
}

// merge places block between the opine markers, leaving everything a person
// wrote outside them untouched.
func merge(existing, block string) string {
	b := strings.Index(existing, Begin)
	e := strings.Index(existing, End)
	if b >= 0 && e > b {
		after := strings.TrimPrefix(existing[e+len(End):], "\n")
		return existing[:b] + block + after
	}
	if strings.TrimSpace(existing) == "" {
		return block
	}
	return strings.TrimRight(existing, "\n") + "\n\n" + block
}

func agentsBlock(always []*record.Record, hasScoped bool, spec *structure.Spec) string {
	var b strings.Builder
	b.WriteString(Begin + "\n" + notice + "\n## Conventions\n\n")
	b.WriteString("Enforced by `opine check`. Run it before you finish and fix what it reports; `opine explain <id>` gives the reason and an example.\n")
	for _, lvl := range []record.Level{record.Must, record.Should} {
		first := true
		for _, r := range always {
			if r.Level != lvl {
				continue
			}
			if first {
				fmt.Fprintf(&b, "\n%s:\n", strings.ToUpper(string(lvl)))
				first = false
			}
			fmt.Fprintf(&b, "- %s (`%s`)\n", sentence(r.Title), r.ID)
		}
	}
	if spec != nil {
		guide := spec.Guide()
		layers := spec.LayerSummary()
		if len(guide) > 0 || layers != "" {
			b.WriteString("\nWhere code goes:\n")
			for _, g := range guide {
				b.WriteString("- " + g + "\n")
			}
			if layers != "" {
				fmt.Fprintf(&b, "- Imports only point down these layers: %s\n", layers)
			}
		}
	}
	if hasScoped {
		b.WriteString("\nMore conventions apply to specific paths. If your tool did not load them for the files you are changing, read the matching entries in `CONVENTIONS.md`.\n")
	}
	b.WriteString(End + "\n")
	return b.String()
}

func sentence(s string) string {
	s = strings.TrimSpace(s)
	if s == "" || strings.HasSuffix(s, ".") || strings.HasSuffix(s, "!") || strings.HasSuffix(s, "?") {
		return s
	}
	return s + "."
}

// card renders one convention in full: the rule, the reason, an example.
func card(r *record.Record) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n", r.Title)
	if r.Why != "" {
		fmt.Fprintf(&b, "\n%s\n", r.Why)
	}
	for _, set := range []struct {
		label string
		ex    []record.Example
	}{{"Bad", r.Bad}, {"Good", r.Good}} {
		for _, e := range set.ex {
			fmt.Fprintf(&b, "\n%s:\n```%s\n%s\n```\n", set.label, e.Lang, e.Code)
		}
	}
	how := "checked by `opine check`"
	if !r.Mechanical() {
		how = "checked in review: " + r.Review
	}
	fmt.Fprintf(&b, "\n_%s · `%s` · %s_\n", r.Level, r.ID, how)
	return b.String()
}

func digest(res *pack.Resolved, spec *structure.Spec) string {
	active := res.Active()
	mech := 0
	for _, r := range active {
		if r.Mechanical() {
			mech++
		}
	}
	var b strings.Builder
	b.WriteString(notice + "\n# Conventions\n\n")
	b.WriteString("How code is written in this repository. One line per convention; follow a link for the reason and an example.\n\n")
	fmt.Fprintf(&b, "**%d in force**: %d checked by machine, %d in review. Run `opine check` to verify and `opine explain <id>` for detail.\n",
		len(active), mech, len(active)-mech)

	undecided := 0
	first := true
	for _, d := range res.Decisions {
		c, ok := res.Config.Decisions[d.ID]
		if !ok {
			undecided++
			continue
		}
		if first {
			b.WriteString("\n## Decisions\n\n| Question | Here |\n|---|---|\n")
			first = false
		}
		fmt.Fprintf(&b, "| %s | **%s** |\n", d.Question, c)
	}
	if undecided > 0 {
		fmt.Fprintf(&b, "\n%s not yet made; `opine decisions` lists them.\n", pluralDecision(undecided))
	}

	if spec != nil {
		if tree := spec.Render(); tree != "" {
			b.WriteString("\n## Structure\n\n```text\n" + tree + "```\n")
			if l := spec.LayerSummary(); l != "" {
				fmt.Fprintf(&b, "\nImports only point down these layers: `%s`\n", l)
			}
		}
	}

	for _, topic := range record.Topics {
		first := true
		for _, r := range active {
			if r.Topic != topic {
				continue
			}
			if first {
				fmt.Fprintf(&b, "\n## %s\n\n", topic)
				first = false
			}
			title := r.Title
			if r.Local {
				title = fmt.Sprintf("[%s](%s)", r.Title, r.Source)
			}
			parts := []string{fmt.Sprintf("**%s** %s", r.Level, title)}
			if !global(r) {
				parts = append(parts, "`"+strings.Join(r.Paths, "`, `")+"`")
			}
			if r.Mechanical() {
				parts = append(parts, "checked")
			} else {
				parts = append(parts, "review")
			}
			if !r.Local {
				parts = append(parts, "from "+r.Layer)
			}
			fmt.Fprintf(&b, "- %s\n", strings.Join(parts, " · "))
		}
	}

	var proposed []*record.Record
	for _, r := range res.Records {
		if r.Status == record.Proposed {
			proposed = append(proposed, r)
		}
	}
	if len(proposed) > 0 {
		fmt.Fprintf(&b, "\n## Proposed\n\n%d awaiting a decision; run `opine review`.\n\n", len(proposed))
		for _, r := range proposed {
			fmt.Fprintf(&b, "- %s (`%s`)\n", r.Title, r.ID)
		}
	}
	return b.String()
}

// Stale lists planned files whose content on disk differs, and files that
// should no longer exist.
func (p *Plan) Stale(root string) []string {
	var out []string
	for _, f := range p.Files {
		if read(root, f.Path) != f.Content || !exists(root, f.Path) {
			out = append(out, f.Path)
		}
	}
	return append(out, p.Remove...)
}

// Write applies the plan and returns the paths it changed.
func (p *Plan) Write(root string) ([]string, error) {
	var changed []string
	for _, f := range p.Files {
		if exists(root, f.Path) && read(root, f.Path) == f.Content {
			continue
		}
		full := filepath.Join(root, filepath.FromSlash(f.Path))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return changed, err
		}
		if err := os.WriteFile(full, []byte(f.Content), 0o644); err != nil {
			return changed, err
		}
		changed = append(changed, f.Path)
	}
	for _, r := range p.Remove {
		if err := os.Remove(filepath.Join(root, filepath.FromSlash(r))); err != nil {
			return changed, err
		}
		changed = append(changed, r+" (removed)")
	}
	return changed, nil
}

func pluralDecision(n int) string {
	if n == 1 {
		return "1 decision"
	}
	return fmt.Sprintf("%d decisions", n)
}
